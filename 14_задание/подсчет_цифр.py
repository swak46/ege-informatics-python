# Условие: значение арифметического выражения 497 + 721 − 7 записали в системе счисления с основанием 7. 
# Сколько цифр 6 содержится в этой записи?
# Создаем функцию перевода в 7-ричную систему счисления
def to_7(n):
    s = ''
    while n > 0:
        s += str(n % 7) # сохраняем остаток в строку
        n //= 7
    return s[::-1] # переворачиваем, возвращаем СТРОКУ
d = to_7(49*7 + 7**21 - 7) # переводим число в 7-ричную систему счисления
print(d.count('6')) # считаем количество цифр 6
# ⚠ВАЖНО: если система основане системы счисления больше 10, остаток сохраняем в список
# т.к. при переводе, например, в 13-ричную систему счисления, остаток может состоять из 2-х символов
# например:
def to_13_wrong(n):
    s = ''
    while n > 0:
        s += str(n % 13)  # Если остаток 11, в строку запишется "11" (два символа)
        n //= 13
    return s[::-1]

# Попробуем перевести число 11. В 13-ричной системе это ОДНА цифра (11)
print(to_13_wrong(11))  # Выведет: "11"
# Если мы захотим посчитать количество единиц:
print(to_13_wrong(11).count('1'))  # Выведет: 2 (А должно быть 0, так как единиц там нет, там цифра 11!)
# верное решение:
def to_13(n):
    s = []  # используем список вместо строки
    while n > 0:
        s.append(n % 13)  # сохраняем остаток как число целиком (например, 11)
        n //= 13
    return s[::-1]  # переворачиваем список

# Попробуем перевести число 11 
print(to_13(11))  # Выведет: [11] (это список из одного элемента)
res = to_13(11)
# Теперь мы можем точно посчитать, сколько раз встретилась конкретная цифра:
print(res.count(1))   # Выведет: 0 (правильно, единиц нет)
print(res.count(11))  # Выведет: 1 (правильно, одна цифра 11)
